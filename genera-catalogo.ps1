
$ErrorActionPreference = "Stop"

try {
    # ==========================================
    # PATHS
    # ==========================================

    $root = $PSScriptRoot
    $songbookPath = Join-Path $root "songbook"
    $jsPath = Join-Path $root "js"
    $outputPath = Join-Path $jsPath "songs-generated.js"

    Write-Host ""
    Write-Host "Cartella progetto: $root"

    if (-not (Test-Path $songbookPath -PathType Container)) {
        throw "Cartella songbook non trovata: $songbookPath"
    }

    if (-not (Test-Path $jsPath -PathType Container)) {
        throw "Cartella js non trovata: $jsPath"
    }

    # ==========================================
    # CONVERT ROMAN NUMERALS TO NUMBERS
    # ==========================================

    function Convert-RomanToNumber([string]$roman) {
        $values = @{
            I = 1
            V = 5
            X = 10
            L = 50
            C = 100
            D = 500
            M = 1000
        }

        $total = 0
        $previous = 0
        $characters = $roman.ToUpper().ToCharArray()

        for ($i = $characters.Length - 1; $i -ge 0; $i--) {
            $value = $values[[string]$characters[$i]]

            if ($value -lt $previous) {
                $total -= $value
            }
            else {
                $total += $value
            }

            $previous = $value
        }

        return $total
    }

    # ==========================================
    # READ ORDER NUMBER
    # ==========================================

    function Get-InitialNumber([string]$name) {
        if ($name -match '^\s*(\d+)') {
            return [int]$Matches[1]
        }

        if ($name -match '^\s*([IVXLCDM]+)(?:[\s._)\-]|$)') {
            return (Convert-RomanToNumber $Matches[1])
        }

        return 999999
    }

    # ==========================================
    # REMOVE NUMBER FROM CATEGORY DISPLAY NAME
    # ==========================================

    function Get-DisplayName([string]$name) {
        return ($name -replace '^\s*\d+\s*[-_. )]*\s*', '').Trim()
    }

    # ==========================================
    # READ AND SORT CATEGORY FOLDERS
    # ==========================================

    $folders = @(
        Get-ChildItem -Path $songbookPath -Directory |
        ForEach-Object {
            [PSCustomObject]@{
                Folder = $_
                Number = Get-InitialNumber $_.Name
                Name   = Get-DisplayName $_.Name
            }
        } |
        Sort-Object Number, Name
    )

    Write-Host "Cartelle trovate: $($folders.Count)"

    $categories = @()
    $totalHtml = 0
    $totalPdf = 0

    # ==========================================
    # READ HTML AND PDF FILES
    # ==========================================

    foreach ($entry in $folders) {
        Write-Host ""
        Write-Host "Controllo categoria: $($entry.Folder.Name)"

        $files = @(
            Get-ChildItem -Path $entry.Folder.FullName -File |
            Where-Object {
                $_.Extension -in @(".htm", ".html", ".pdf")
            } |
            ForEach-Object {
                [PSCustomObject]@{
                    File   = $_
                    Number = Get-InitialNumber $_.BaseName
                    Name   = $_.BaseName
                    Type   = if ($_.Extension -ieq ".pdf") {
                        "pdf"
                    }
                    else {
                        "html"
                    }
                }
            } |
            Sort-Object Number, Name, Type
        )

        if ($files.Count -eq 0) {
            Write-Host "  Nessun file HTML o PDF trovato."
            continue
        }

        $songs = @(
            foreach ($item in $files) {
                $relativePath = "songbook/" +
                    $entry.Folder.Name + "/" +
                    $item.File.Name

                if ($item.Type -eq "pdf") {
                    $totalPdf++
                }
                else {
                    $totalHtml++
                }

                [PSCustomObject]@{
                    title = $item.File.BaseName
                    file  = $relativePath
                    type  = $item.Type
                }
            }
        )

        $categories += [PSCustomObject]@{
            id        = "category-" + $entry.Folder.Name
            name      = $entry.Name
            songs     = $songs
            songbooks = @()
        }

        Write-Host "  File trovati: $($files.Count)"
        Write-Host "  HTML: $(($files | Where-Object { $_.Type -eq 'html' }).Count)"
        Write-Host "  PDF:  $(($files | Where-Object { $_.Type -eq 'pdf' }).Count)"
    }

    # ==========================================
    # GENERATE JAVASCRIPT FILE
    # ==========================================

    $json = ConvertTo-Json -InputObject @($categories) -Depth 8

    $content = @"
// Generated automatically by AggiornaCanti.bat.
// Do not edit this file manually.

const songCategories = $json;
"@

    $encoding = New-Object System.Text.UTF8Encoding($false)

    [System.IO.File]::WriteAllText(
        $outputPath,
        $content,
        $encoding
    )

    # ==========================================
    # VERIFY OUTPUT
    # ==========================================

    if (-not (Test-Path $outputPath -PathType Leaf)) {
        throw "Il file generato non esiste: $outputPath"
    }

    $generatedFile = Get-Item $outputPath

    Write-Host ""
    Write-Host "========================================"
    Write-Host "CATALOGO AGGIORNATO CORRETTAMENTE!" -ForegroundColor Green
    Write-Host "Categorie create: $($categories.Count)"
    Write-Host "Canti HTML: $totalHtml"
    Write-Host "File PDF:   $totalPdf"
    Write-Host "File generato: $($generatedFile.FullName)"
    Write-Host "Dimensione: $($generatedFile.Length) byte"
    Write-Host "========================================"
    Write-Host ""

    exit 0
}
catch {
    Write-Host ""
    Write-Host "ERRORE DURANTE LA GENERAZIONE!" -ForegroundColor Red
    Write-Host $_.Exception.Message -ForegroundColor Red
    Write-Host ""

    exit 1
}
